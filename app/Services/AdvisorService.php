<?php
declare(strict_types=1);

namespace FinSync\Services;

use FinSync\Core\Database;
use Throwable;

final class AdvisorService
{
    /**
     * Generate dynamic AI insights grounded in the user's real financial data.
     * Uses OpenAI or Gemini API when configured; otherwise runs FinSync's Autonomous
     * Financial Intelligence Engine for instant, mathematically grounded insights.
     */
    public function respond(string $question, array $context): array
    {
        $config = Database::config();
        $openaiKey = trim((string)($config['openai']['api_key'] ?? ''));
        $openaiEnabled = (bool)($config['openai']['enabled'] ?? false);
        $geminiKey = trim((string)($config['gemini']['api_key'] ?? ''));
        $geminiEnabled = (bool)($config['gemini']['enabled'] ?? false);

        // Normalize financial context
        $overview = $context['overview'] ?? $context;
        $pf = $context['personal_finance'] ?? [];
        $income = (float)($overview['monthly_income'] ?? ($pf['monthly_income'] ?? 0));
        $otherIncome = (float)($pf['other_income'] ?? 0);
        $totalIncome = $income + $otherIncome;
        $expenses = (float)($overview['monthly_expenses'] ?? ($pf['monthly_expenses'] ?? 0));
        $net = $totalIncome - $expenses;
        $savings = (float)($pf['savings'] ?? 0);
        $investmentsVal = (float)($overview['investment_value'] ?? ($pf['investments'] ?? 0));
        $loansDebt = (float)($pf['loans_debt'] ?? 0);
        $creditCard = (float)($pf['credit_card_balance'] ?? 0);
        $totalDebt = $loansDebt + $creditCard;
        $netWorth = (float)($overview['net_worth'] ?? (($savings + $investmentsVal) - $totalDebt));
        $savingsRate = $totalIncome > 0 ? round(($net / $totalIncome) * 100, 1) : 0.0;
        $emergencyMonths = $expenses > 0 ? round($savings / $expenses, 1) : 0.0;
        $dti = $totalIncome > 0 ? round(($totalDebt / $totalIncome) * 100, 1) : 0.0;

        $categoryExpenses = $context['category_expenses'] ?? [];
        $budgets = $context['budgets'] ?? [];
        $brokers = $context['brokers'] ?? [];
        $holdings = $context['holdings'] ?? [];

        // Build rich prompt for external LLM (if configured)
        $externalContext = $this->buildContextSummary(
            $totalIncome, $expenses, $net, $savingsRate, $savings,
            $investmentsVal, $totalDebt, $netWorth, $emergencyMonths,
            $categoryExpenses, $budgets, $brokers, $holdings
        );

        // Check if OpenAI is enabled and configured
        if ($openaiEnabled && $openaiKey !== '') {
            $model = $config['openai']['model'] ?? 'gpt-4o-mini';
            try {
                $aiAnswer = $this->queryOpenAi($openaiKey, $model, $question, $externalContext);
                return [
                    'answer'     => $aiAnswer,
                    'mode'       => 'live_ai_openai',
                    'model'      => $model,
                    'disclaimer' => 'Generated by OpenAI based on your real FinSync data. Not professional financial advice.',
                ];
            } catch (Throwable $e) {
                error_log('OpenAI API Error: ' . $e->getMessage());
                // Fall through to Autonomous Financial Intelligence Engine
            }
        }

        // Check if Gemini is enabled and configured
        if ($geminiEnabled && $geminiKey !== '') {
            $model = $config['gemini']['model'] ?? 'gemini-1.5-flash';
            try {
                $aiAnswer = $this->queryGemini($geminiKey, $model, $question, $externalContext);
                return [
                    'answer'     => $aiAnswer,
                    'mode'       => 'live_ai_gemini',
                    'model'      => $model,
                    'disclaimer' => 'Generated by Google Gemini based on your real FinSync data. Not professional financial advice.',
                ];
            } catch (Throwable $e) {
                error_log('Gemini API Error: ' . $e->getMessage());
                // Fall through to Autonomous Financial Intelligence Engine
            }
        }

        // Autonomous Financial Intelligence Engine
        $autonomousInsight = $this->generateAutonomousInsight(
            $question,
            $totalIncome,
            $expenses,
            $net,
            $savingsRate,
            $savings,
            $investmentsVal,
            $totalDebt,
            $loansDebt,
            $creditCard,
            $netWorth,
            $emergencyMonths,
            $dti,
            $categoryExpenses,
            $budgets,
            $brokers,
            $holdings
        );

        return [
            'answer'     => $autonomousInsight,
            'mode'       => 'live_builtin_ai',
            'model'      => 'FinSync Financial Intelligence v2.0',
            'disclaimer' => 'FinSync Autonomous Intelligence · Calculated directly from your real MySQL records.',
        ];
    }

    /**
     * FinSync Autonomous Financial Intelligence Engine.
     * Evaluates user query intent and performs mathematically grounded financial analysis.
     */
    private function generateAutonomousInsight(
        string $question,
        float $income,
        float $expenses,
        float $net,
        float $savingsRate,
        float $savings,
        float $investments,
        float $totalDebt,
        float $loansDebt,
        float $creditCard,
        float $netWorth,
        float $emergencyMonths,
        float $dti,
        array $categoryExpenses,
        array $budgets,
        array $brokers,
        array $holdings
    ): string {
        $q = strtolower(trim($question));

        // 1. INVESTMENTS & MULTI-BROKER INTENT (Zerodha, Dhan, Groww)
        if (str_contains($q, 'invest') || str_contains($q, 'stock') || str_contains($q, 'portfolio') ||
            str_contains($q, 'broker') || str_contains($q, 'zerodha') || str_contains($q, 'dhan') ||
            str_contains($q, 'groww') || str_contains($q, 'holding') || str_contains($q, 'return') ||
            str_contains($q, 'pnl') || str_contains($q, 'demat')) {
            return $this->analyzeInvestmentsIntent($investments, $brokers, $holdings);
        }

        // 2. EXPENSES & SPENDING INTENT
        if (str_contains($q, 'spend') || str_contains($q, 'expense') || str_contains($q, 'cost') ||
            str_contains($q, 'outflow') || str_contains($q, 'cut') || str_contains($q, 'bill') ||
            str_contains($q, 'food') || str_contains($q, 'shopping')) {
            return $this->analyzeSpendingIntent($income, $expenses, $net, $savingsRate, $categoryExpenses, $budgets);
        }

        // 3. BUDGET & SAVINGS INTENT
        if (str_contains($q, 'budget') || str_contains($q, 'save') || str_contains($q, 'saving') ||
            str_contains($q, 'target') || str_contains($q, 'rule') || str_contains($q, '50/30/20')) {
            return $this->analyzeBudgetIntent($income, $expenses, $net, $savingsRate, $budgets, $categoryExpenses);
        }

        // 4. EMERGENCY FUND & DEBT INTENT
        if (str_contains($q, 'emergency') || str_contains($q, 'debt') || str_contains($q, 'loan') ||
            str_contains($q, 'credit card') || str_contains($q, 'safety') || str_contains($q, 'runway') ||
            str_contains($q, 'dti') || str_contains($q, 'liability')) {
            return $this->analyzeSafetyIntent($savings, $expenses, $emergencyMonths, $totalDebt, $loansDebt, $creditCard, $dti);
        }

        // 5. DEFAULT: COMPREHENSIVE FINANCIAL HEALTH AUDIT
        return $this->analyzeComprehensiveHealth(
            $income, $expenses, $net, $savingsRate, $savings,
            $investments, $totalDebt, $netWorth, $emergencyMonths,
            $dti, $categoryExpenses, $budgets, $brokers, $holdings
        );
    }

    private function analyzeInvestmentsIntent(float $totalVal, array $brokers, array $holdings): string
    {
        $lines = [];
        $lines[] = "### 📊 Multi-Broker Portfolio Analysis (Zerodha • Dhan • Groww)\n";

        // Broker breakdown
        $zVal = (float)($brokers['zerodha']['total_value'] ?? 0);
        $dVal = (float)($brokers['dhan']['total_value'] ?? 0);
        $gVal = (float)($brokers['groww']['total_value'] ?? 0);
        $zStatus = $brokers['zerodha']['status'] ?? 'disconnected';
        $dStatus = $brokers['dhan']['status'] ?? 'disconnected';
        $gStatus = $brokers['groww']['status'] ?? 'disconnected';

        $lines[] = "**Active Broker Integrations:**";
        $lines[] = sprintf("• **Zerodha Kite:** %s (₹%s · %d holdings)", 
            $zStatus === 'connected' ? '🟢 Active' : '⚪ Disconnected',
            number_format($zVal, 2),
            (int)($brokers['zerodha']['holdings_count'] ?? 0)
        );
        $lines[] = sprintf("• **DhanHQ API (v2):** %s (₹%s · %d holdings)", 
            $dStatus === 'connected' ? '🟢 Active' : ($dStatus === 'token_expired' ? '🟡 Token Expired' : '⚪ Disconnected'),
            number_format($dVal, 2),
            (int)($brokers['dhan']['holdings_count'] ?? 0)
        );
        $lines[] = sprintf("• **Groww Demat:** %s (₹%s · %d holdings)", 
            $gStatus === 'connected' ? '🟢 Active' : '⚪ Disconnected',
            number_format($gVal, 2),
            (int)($brokers['groww']['holdings_count'] ?? 0)
        );

        $lines[] = sprintf("\n**Total Portfolio Value:** ₹%s across %d instruments.\n", 
            number_format($totalVal, 2), 
            count($holdings)
        );

        if (!empty($holdings)) {
            $totalCost = 0.0;
            $totalPnl = 0.0;
            $topHoldings = [];

            foreach ($holdings as $h) {
                $mVal = (float)($h['market_value'] ?? 0);
                $units = (float)($h['units'] ?? 0);
                $buy = (float)($h['buy_price'] ?? 0);
                $cost = $buy > 0 ? $buy * $units : $mVal;
                $pnl = isset($h['pnl']) && $h['pnl'] !== null ? (float)$h['pnl'] : ($mVal - $cost);
                $totalCost += $cost;
                $totalPnl += $pnl;
                $topHoldings[] = ['symbol' => $h['symbol'], 'val' => $mVal, 'pnl' => $pnl];
            }

            usort($topHoldings, static fn($a, $b) => $b['val'] <=> $a['val']);
            $pnlPct = $totalCost > 0 ? round(($totalPnl / $totalCost) * 100, 2) : 0.0;

            $lines[] = "**Returns & P&L Performance:**";
            $lines[] = sprintf("• Total Invested Capital: ₹%s", number_format($totalCost, 2));
            $lines[] = sprintf("• Unrealized Profit/Loss: %s₹%s (%s%s%%)", 
                $totalPnl >= 0 ? '+' : '', number_format($totalPnl, 2),
                $totalPnl >= 0 ? '+' : '', $pnlPct
            );

            $lines[] = "\n**Top Holdings by Allocation:**";
            foreach (array_slice($topHoldings, 0, 4) as $th) {
                $share = $totalVal > 0 ? round(($th['val'] / $totalVal) * 100, 1) : 0;
                $lines[] = sprintf("• **%s:** ₹%s (%s%% of portfolio)", $th['symbol'], number_format($th['val'], 2), $share);
            }

            // Concentration risk advisory
            $topShare = $totalVal > 0 ? round(($topHoldings[0]['val'] / $totalVal) * 100, 1) : 0;
            $lines[] = "\n**💡 AI Portfolio Guidance:**";
            if ($topShare > 30) {
                $lines[] = sprintf("⚠️ **Concentration Risk:** Your top holding (%s) represents %s%% of your portfolio. Consider rebalancing across diversified large-cap or index ETFs to cushion against individual stock volatility.", $topHoldings[0]['symbol'], $topShare);
            } else {
                $lines[] = "✅ **Healthy Diversification:** No single equity dominates >30% of your holdings, preserving balanced risk exposure.";
            }
            if ($dStatus === 'disconnected' || $zStatus === 'disconnected') {
                $lines[] = "👉 **Multi-Broker Tip:** Connect your remaining Demat accounts (Dhan or Zerodha) to get an aggregated single-pane view of your entire Indian net worth.";
            }
        } else {
            $lines[] = "💡 **Next Steps:** Link your Zerodha Kite or Dhan account above, or import your Groww CSV statement to see live portfolio performance and real-time stock insights.";
        }

        return implode("\n", $lines);
    }

    private function analyzeSpendingIntent(
        float $income,
        float $expenses,
        float $net,
        float $savingsRate,
        array $categoryExpenses,
        array $budgets
    ): string {
        $lines = [];
        $lines[] = "### 💳 Monthly Spending & Outflow Analysis\n";
        $lines[] = sprintf("**Total Monthly Outflow:** ₹%s (Net Cash Flow: %s₹%s · %s%% savings rate)\n", 
            number_format($expenses, 2),
            $net >= 0 ? '+' : '', number_format($net, 2),
            $savingsRate
        );

        if (!empty($categoryExpenses)) {
            $lines[] = "**Top Spending Categories This Month:**";
            foreach (array_slice($categoryExpenses, 0, 5) as $cat) {
                $amt = (float)$cat['total'];
                $pct = $expenses > 0 ? round(($amt / $expenses) * 100, 1) : 0;
                $lines[] = sprintf("• **%s:** ₹%s (%s%% of total spending)", $cat['category'], number_format($amt, 2), $pct);
            }

            // Check against budgets
            if (!empty($budgets)) {
                $lines[] = "\n**Budget Adherence:**";
                $overCount = 0;
                foreach ($budgets as $b) {
                    $catName = (string)$b['category'];
                    $limit = (float)$b['monthly_limit'];
                    $spent = 0.0;
                    foreach ($categoryExpenses as $c) {
                        if (strcasecmp((string)$c['category'], $catName) === 0) {
                            $spent = (float)$c['total'];
                            break;
                        }
                    }
                    $pct = $limit > 0 ? round(($spent / $limit) * 100, 1) : 0;
                    if ($spent > $limit) {
                        $overCount++;
                        $lines[] = sprintf("⚠️ **%s Over Budget:** ₹%s spent of ₹%s limit (%s%%)", $catName, number_format($spent, 2), number_format($limit, 2), $pct);
                    } elseif ($pct >= 80) {
                        $lines[] = sprintf("🟡 **%s Approaching Limit:** ₹%s spent of ₹%s limit (%s%%)", $catName, number_format($spent, 2), number_format($limit, 2), $pct);
                    }
                }
                if ($overCount === 0) {
                    $lines[] = "✅ All monitored expense categories are operating comfortably within their monthly limits.";
                }
            }
        } else {
            $lines[] = "• Monthly living expenses logged: ₹" . number_format($expenses, 2);
            $lines[] = "• Tip: Add individual expense transactions in the **Expenses** screen to view detailed category breakdown and daily burn rate.";
        }

        $lines[] = "\n**💡 AI Recommendation:**";
        if ($savingsRate < 20) {
            $lines[] = "• Your current savings rate is " . $savingsRate . "%. The golden standard is at least 20%. Consider auditing discretionary spending in dining and shopping to boost your monthly net surplus.";
        } else {
            $lines[] = "• Outstanding discipline! Your savings rate of " . $savingsRate . "% exceeds the recommended 20% benchmark. Direct surplus capital into SIPs or high-yield savings.";
        }

        return implode("\n", $lines);
    }

    private function analyzeBudgetIntent(
        float $income,
        float $expenses,
        float $net,
        float $savingsRate,
        array $budgets,
        array $categoryExpenses
    ): string {
        $lines = [];
        $lines[] = "### 🎯 Budget Adherence & 50/30/20 Allocation\n";

        // 50/30/20 Benchmark
        $targetNeeds = $income * 0.50;
        $targetWants = $income * 0.30;
        $targetSavings = $income * 0.20;

        $lines[] = "**50/30/20 Ideal Allocation Comparison:**";
        $lines[] = sprintf("• **Needs (50%% target):** Ideal ₹%s | Current living expenses: ₹%s", number_format($targetNeeds, 2), number_format($expenses, 2));
        $lines[] = sprintf("• **Savings & Investments (20%% target):** Ideal ₹%s | Current monthly surplus: ₹%s (%s%%)", 
            number_format($targetSavings, 2), number_format($net, 2), $savingsRate
        );

        if (!empty($budgets)) {
            $lines[] = "\n**Active Category Budgets:**";
            foreach ($budgets as $b) {
                $catName = (string)$b['category'];
                $limit = (float)$b['monthly_limit'];
                $spent = 0.0;
                foreach ($categoryExpenses as $c) {
                    if (strcasecmp((string)$c['category'], $catName) === 0) {
                        $spent = (float)$c['total'];
                        break;
                    }
                }
                $pct = $limit > 0 ? round(($spent / $limit) * 100, 1) : 0;
                $lines[] = sprintf("• **%s:** ₹%s / ₹%s (%s%% utilized)", $catName, number_format($spent, 2), number_format($limit, 2), $pct);
            }
        } else {
            $lines[] = "\n💡 **Tip:** Set category budgets in the **Expenses** screen to receive real-time alerts before you overspend.";
        }

        $lines[] = "\n**Actionable Step:**";
        if ($net < 0) {
            $lines[] = "⚠️ **Deficit Alert:** Your monthly expenses exceed income by ₹" . number_format(abs($net), 2) . ". Prioritize trimming flexible expenses immediately to stop debt accumulation.";
        } elseif ($savingsRate >= 20) {
            $lines[] = "✅ **On Track:** Your savings rate meets the 20% rule. Automatically transfer ₹" . number_format($net, 2) . " into your Zerodha/Dhan Demat or emergency reserve on salary day.";
        } else {
            $lines[] = "💡 **Improvement Area:** Aim to increase your monthly savings rate from " . $savingsRate . "% to 20% (₹" . number_format($targetSavings, 2) . ") by capping non-essential categories.";
        }

        return implode("\n", $lines);
    }

