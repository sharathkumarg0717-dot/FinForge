        $lines[] = sprintf("**Emergency Fund:** ₹%s (covers **%s months** of essential living expenses)\n", 
            number_format($savings, 2), $emergencyMonths
        );

        $lines[] = "**Financial Safety Benchmark:**";
        if ($emergencyMonths >= 6) {
            $lines[] = "✅ **Rock-solid Safety:** You have 6+ months of living expenses safely banked, providing full immunity against unexpected income disruptions.";
        } elseif ($emergencyMonths >= 3) {
            $lines[] = "🟡 **Adequate Runway:** You have 3-5 months of runway. Aim to build towards the gold standard of 6 months (₹" . number_format($expenses * 6, 2) . ").";
        } else {
            $lines[] = "⚠️ **Low Reserve Warning:** Current savings cover under 3 months. Prioritize building an emergency buffer of at least ₹" . number_format($expenses * 3, 2) . " before making aggressive equity bets.";
        }

        $lines[] = "\n**Debt & Liability Breakdown:**";
        $lines[] = sprintf("• Total Debt: ₹%s", number_format($totalDebt, 2));
        if ($loansDebt > 0) $lines[] = sprintf("  - Term Loans: ₹%s", number_format($loansDebt, 2));
