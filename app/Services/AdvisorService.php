    private function queryGemini(string $apiKey, string $model, string $question, string $context): string
    {
        $systemPrompt = "You are FinSync's senior FinTech AI financial intelligence advisor. " .
            "Analyze the user's real financial metrics provided below and answer their question clearly, " .
            "concisely, and objectively. Highlight strengths, potential risks, and practical suggestions. " .
            "Always format numbers in Indian Rupees (₹). Keep the tone helpful, professional, and grounded strictly in their actual numbers.\n\n" .
            "User's Real Financial Context:\n" . $context;

        $url = "https://generativelanguage.googleapis.com/v1beta/models/{$model}:generateContent?key=" . urlencode($apiKey);

        $payload = [
            'contents' => [
                [
                    'role' => 'user',
                    'parts' => [
                        ['text' => $systemPrompt . "\n\nUser Question: " . $question],
                    ],
                ],
            ],
            'generationConfig' => [
                'temperature' => 0.4,
                'maxOutputTokens' => 800,
            ],
        ];

        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_POST           => true,
            CURLOPT_POSTFIELDS     => json_encode($payload),
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_HTTPHEADER     => ['Content-Type: application/json'],
            CURLOPT_TIMEOUT        => 15,
            CURLOPT_SSL_VERIFYPEER => true,
        ]);

        $response = curl_exec($ch);
        $httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $err = curl_error($ch);
        curl_close($ch);

        if ($err) {
            throw new \RuntimeException('cURL error: ' . $err);
        }

        $json = json_decode((string)$response, true);
        if ($httpCode !== 200) {
            $msg = $json['error']['message'] ?? "HTTP {$httpCode} from Gemini";
            throw new \RuntimeException($msg);
        }

        $candidates = $json['candidates'] ?? [];
        if (empty($candidates)) {
            throw new \RuntimeException('No answer generated by Gemini.');
        }

        return (string)($candidates[0]['content']['parts'][0]['text'] ?? 'No text generated by Gemini.');
    }
