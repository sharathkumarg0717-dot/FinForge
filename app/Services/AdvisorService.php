    private function buildContextSummary(
        float $income, float $expenses, float $net, float $savingsRate,
        float $savings, float $investments, float $totalDebt, float $netWorth,
        float $emergencyMonths, array $categoryExpenses, array $budgets,
        array $brokers, array $holdings
    ): string {
        $summary = sprintf(
            "Monthly Inflow: ₹%s\nMonthly Outflow: ₹%s\nNet Surplus: ₹%s (Savings Rate: %s%%)\nCash Savings: ₹%s (Emergency Runway: %s months)\nTotal Investments: ₹%s\nTotal Debt: ₹%s\nNet Worth: ₹%s\n",
            number_format($income, 2), number_format($expenses, 2), number_format($net, 2),
            $savingsRate, number_format($savings, 2), $emergencyMonths,
            number_format($investments, 2), number_format($totalDebt, 2), number_format($netWorth, 2)
        );

        if (!empty($categoryExpenses)) {
            $summary .= "\nTop Spending Categories:\n";
            foreach (array_slice($categoryExpenses, 0, 5) as $c) {
                $summary .= sprintf("- %s: ₹%s\n", $c['category'], number_format((float)$c['total'], 2));
            }
        }

        if (!empty($brokers)) {
            $summary .= "\nConnected Brokers:\n";
            foreach ($brokers as $code => $b) {
                $summary .= sprintf("- %s: %s (Holdings: %d, Value: ₹%s)\n", 
                    $b['broker_name'] ?? $code, $b['status'] ?? 'unknown',
                    (int)($b['holdings_count'] ?? 0), number_format((float)($b['total_value'] ?? 0), 2)
                );
            }
        }

        return $summary;
    }

    private function queryOpenAi(string $apiKey, string $model, string $question, string $context): string
    {
        $systemPrompt = "You are FinSync's senior FinTech AI financial intelligence advisor. " .
            "Analyze the user's real financial metrics provided below and answer their question clearly, " .
            "concisely, and objectively. Highlight strengths, potential risks, and practical suggestions. " .
            "Always format numbers in Indian Rupees (₹). Keep the tone helpful, professional, and grounded strictly in their actual numbers.\n\n" .
            "User's Real Financial Context:\n" . $context;

        $payload = [
            'model' => $model,
            'messages' => [
                ['role' => 'system', 'content' => $systemPrompt],
                ['role' => 'user', 'content' => $question],
            ],
            'temperature' => 0.4,
            'max_tokens'  => 800,
        ];

        $ch = curl_init('https://api.openai.com/v1/chat/completions');
        curl_setopt_array($ch, [
            CURLOPT_POST           => true,
            CURLOPT_POSTFIELDS     => json_encode($payload),
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_HTTPHEADER     => [
                'Content-Type: application/json',
                'Authorization: Bearer ' . $apiKey,
            ],
            CURLOPT_TIMEOUT        => 15,
            CURLOPT_SSL_VERIFYPEER => true,
        ]);

        $response = curl_exec($ch);
